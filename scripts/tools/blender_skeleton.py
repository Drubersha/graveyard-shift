def _rot(v, r):
    """Godot-совместимый поворот YXZ (градусы) вокруг локального нуля детали."""
    x, y, z = v
    rx, ry, rz = [math.radians(a) for a in r]
    # Z
    c, s = math.cos(rz), math.sin(rz)
    x, y = x * c - y * s, x * s + y * c
    # X
    c, s = math.cos(rx), math.sin(rx)
    y, z = y * c - z * s, y * s + z * c
    # Y
    c, s = math.cos(ry), math.sin(ry)
    x, z = x * c + z * s, -x * s + z * c
    return (x, y, z)


def box(size, pos, mat, rot=(0, 0, 0)):
    hx, hy, hz = size[0] / 2.0, size[1] / 2.0, size[2] / 2.0
    raw = [(-hx, -hy, -hz), (hx, -hy, -hz), (hx, -hy, hz), (-hx, -hy, hz),
           (-hx, hy, -hz), (hx, hy, -hz), (hx, hy, hz), (-hx, hy, hz)]
    verts = [tuple(a + b for a, b in zip(_rot(v, rot), pos)) for v in raw]
    faces = [(0, 1, 2, 3), (7, 6, 5, 4), (0, 4, 5, 1),
             (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]
    return (verts, faces, mat)


def prism(rings, sides, mat, pos=(0, 0, 0)):
    """Гранёная призма по кольцам (радиус_X, Y, радиус_Z) — как MeshLib.faceted.

    ЧЁТНОЕ число сторон обязательно там, где важна симметрия левое/правое:
    при нечётном (было 7 у черепной коробки) кольцо симметрично только
    перёд/зад, слева получается ребро, справа грань — и на макро это видно.
    """
    verts, faces = [], []
    loops = []
    for (rx, y, rz) in rings:
        idx = []
        for i in range(sides):
            a = TAU * (i + 0.5) / sides
            idx.append(len(verts))
            verts.append((math.cos(a) * rx + pos[0], y + pos[1], math.sin(a) * rz + pos[2]))
        loops.append(idx)
    for li in range(len(loops) - 1):
        lo, hi = loops[li], loops[li + 1]
        for i in range(sides):
            j = (i + 1) % sides
            faces.append((lo[i], hi[i], hi[j], lo[j]))
    cb = len(verts)
    verts.append((pos[0], rings[0][1] + pos[1], pos[2]))
    ct = len(verts)
    verts.append((pos[0], rings[-1][1] + pos[1], pos[2]))
    for i in range(sides):
        j = (i + 1) % sides
        faces.append((cb, loops[0][j], loops[0][i]))
        faces.append((ct, loops[-1][i], loops[-1][j]))
    return (verts, faces, mat)


def _norm(v):
    l = math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2])
    return (v[0] / l, v[1] / l, v[2] / l) if l > 1e-9 else (0.0, 0.0, 1.0)


def _cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def sweep(points, radii, sides, mat):
    """Труба по ломаной: в каждой точке кольцо в плоскости, перпендикулярной пути.

    Нужна ровно для рёбер. Ребро из трёх прямых коробок (бок + перед + зад)
    читалось доской: у коробки постоянная толщина, прямые торцы и один тон на
    всю грань. Развёртка по дуге даёт непрерывный изгиб и разные по светлоте
    фасетки вдоль ребра — кость, а не планка.

    radii — список пар (наружу, вверх) на каждую точку: ребро это ЛЕЗВИЕ,
    поперёк тонкое, по высоте вдвое шире.
    """
    verts, faces, loops = [], [], []
    n = len(points)
    for i, p in enumerate(points):
        if i == 0:
            d = [points[1][k] - points[0][k] for k in range(3)]
        elif i == n - 1:
            d = [points[-1][k] - points[-2][k] for k in range(3)]
        else:
            d = [points[i + 1][k] - points[i - 1][k] for k in range(3)]
        d = _norm(d)
        # опорная вертикаль; если путь сам почти вертикален — берём X
        up = (1.0, 0.0, 0.0) if abs(d[1]) > 0.95 else (0.0, 1.0, 0.0)
        u = _norm(_cross(d, up))     # наружу из клетки
        v = _norm(_cross(d, u))      # вверх вдоль ребра
        ru, rv = radii[i]
        idx = []
        for k in range(sides):
            a = TAU * (k + 0.5) / sides
            ca, sa = math.cos(a) * ru, math.sin(a) * rv
            idx.append(len(verts))
            verts.append(tuple(p[j] + u[j] * ca + v[j] * sa for j in range(3)))
        loops.append(idx)
    for li in range(len(loops) - 1):
        lo, hi = loops[li], loops[li + 1]
        for k in range(sides):
            j = (k + 1) % sides
            faces.append((lo[k], hi[k], hi[j], lo[j]))
    cb = len(verts)
    verts.append(tuple(points[0]))
    ct = len(verts)
    verts.append(tuple(points[-1]))
    for k in range(sides):
        j = (k + 1) % sides
        faces.append((cb, loops[0][j], loops[0][k]))
        faces.append((ct, loops[-1][k], loops[-1][j]))
    return (verts, faces, mat)


