def get_materials():
    out = []
    for name, rgba, ek in MATS:
        m = bpy.data.materials.get(name)
        if m is None:
            m = bpy.data.materials.new(name)
        m.use_nodes = True
        bsdf = m.node_tree.nodes.get("Principled BSDF")
        if bsdf:
            bsdf.inputs["Base Color"].default_value = rgba
            if "Roughness" in bsdf.inputs:
                bsdf.inputs["Roughness"].default_value = 0.92
            if "Metallic" in bsdf.inputs:
                bsdf.inputs["Metallic"].default_value = 0.0
            if "Emission Color" in bsdf.inputs:
                bsdf.inputs["Emission Color"].default_value = (
                    rgba[0] * ek, rgba[1] * ek, rgba[2] * ek, 1.0)
            if "Emission Strength" in bsdf.inputs:
                bsdf.inputs["Emission Strength"].default_value = 1.0
        m.diffuse_color = rgba
        out.append(m)
    return out


def make_object(name, chunks, mats):
    """Материалы к мешу цепляются ТОЛЬКО те, что реально использованы: иначе в
    каждом gltf лежали бы все десять, и промер материалов стал бы бессмысленным."""
    used = []
    for (_vs, _fs, mi) in chunks:
        if mi not in used:
            used.append(mi)
    remap = {mi: i for i, mi in enumerate(used)}
    verts, faces, mat_of_face = [], [], []
    for (vs, fs, mi) in chunks:
        base = len(verts)
        # игровые координаты -> блендеровские: bx = gx, by = -gz, bz = gy
        verts.extend([(v[0], -v[2], v[1]) for v in vs])
        for f in fs:
            faces.append(tuple(base + i for i in f))
            mat_of_face.append(remap[mi])
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], faces)
    me.update()
    for mi in used:
        me.materials.append(mats[mi])
    for i, poly in enumerate(me.polygons):
        poly.material_index = mat_of_face[i]
        poly.use_smooth = False           # плоское затенение: фасетки видны
    obj = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(obj)
    return obj


def export(obj, name):
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    path = os.path.join(OUT, name + ".gltf")
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLTF_SEPARATE",
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_materials="EXPORT",
        export_texcoords=True,
        export_normals=True,
        export_cameras=False,
        export_lights=False,
    )
    return path


def run():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    mats = get_materials()
    report = []
    over = []
    for name, fn in PARTS.items():
        obj = make_object(name, fn(), mats)
        d = obj.dimensions
        bb = [v[:] for v in obj.bound_box]
        zmin = min(v[2] for v in bb)
        zmax = max(v[2] for v in bb)
        nmat = len(obj.data.materials)
        export(obj, name)
        report.append("%-20s габарит(игровой XYZ)=%.3f %.3f %.3f  по Y: %.3f..%.3f  полигонов=%d  материалов=%d%s"
                      % (name, d.x, d.z, d.y, zmin, zmax,
                         len(obj.data.polygons), nmat,
                         "" if nmat <= MAX_MATS else "  <-- ПЕРЕБОР"))
        if nmat > MAX_MATS:
            over.append("%s: %d материалов из %s ([%s])"
                        % (name, nmat, MAX_MATS,
                           ", ".join(m.name for m in obj.data.materials)))
        bpy.data.objects.remove(obj, do_unlink=True)
    # Норма стиля проверяется ЗДЕСЬ, при сборке, а не «замечается на кадре».
    # Именно так перебор и прожил до критика: считать материалы вручную никто
    # не собирался.
    if over:
        report.append("")
        report.append("ПЕРЕБОР МАТЕРИАЛОВ (норма %d на деталь):" % MAX_MATS)
        report.extend("  " + s for s in over)
    else:
        report.append("")
        report.append("материалов на деталь: норма %d соблюдена везде" % MAX_MATS)
    return "\n".join(report)


print(run())
