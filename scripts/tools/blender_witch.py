def skirt():
    """Пышная короткая юбка. Начало — таз.

    ВЕРХ ЮБКИ ТЕПЕРЬ СПЛОШНОЙ КОЛОКОЛ, И ЭТО ИСПРАВЛЕНИЕ, А НЕ ВКУСОВЩИНА.
    Раньше юбка целиком собиралась из десяти отдельных клиньев с щелями между
    ними, и начинались клинья с радиуса 0.208 — ровно там, где проходит
    поверхность трусов (0.204 плюс 0.004 на крапинку). Из этого выходило два
    дефекта разом: сквозь щели на уровне таза лезли отдельные белые и синие
    треугольники, а сами клинья отходили от бедра и читались набором лопастей,
    а не юбкой.

    Теперь до уровня -0.170 идёт закрытая гранёная поверхность на радиусе от
    0.228: щелей на уровне таза нет физически, а до трусов остаётся больше двух
    сантиметров. На лопасти юбка распадается только НИЖЕ таза, у подола, где
    рваный край и задуман."""
    # кокетка: садится на оборку корсажа и уходит в колокол без ступеньки
    p = [prism([(0.222, 0.072, 0.200), (0.232, 0.020, 0.209),
                (0.228, -0.006, 0.205)], 12, M_TRIM)]
    sides = 12
    # закрытый колокол; последнее кольцо — рим, с которого свисает подол
    rim_r, rim_y = 0.332, -0.170
    p.append(prism([(0.228, -0.006, 0.205), (0.258, -0.062, 0.232),
                    (0.296, -0.118, 0.266), (rim_r, rim_y, rim_r * 0.90)],
                   sides, M_DRESS))
    # Подол: по створке на каждую грань колокола, во всю ширину грани, поэтому
    # створки СТЫКУЮТСЯ, а не висят по отдельности. Рваным подол делает разная
    # длина, а не щели между створками.
    span = TAU / sides
    for i in range(sides):
        # prism ставит ВЕРШИНЫ на углах TAU*(i+0.5)/sides, значит центр грани — на
        # TAU*(i+1)/sides. Створка центрируется по грани, и её края попадают ровно
        # в рёбра колокола: стык без щели и без ступеньки.
        a = TAU * (i + 1.0) / sides
        wob = math.sin(i * 2.7) * 0.5 + math.sin(i * 1.3) * 0.5
        # Передние створки короче: сидя бедро уходит вперёд, и длинная передняя
        # створка протыкала ногу насквозь. Сзади длина остаётся полной.
        front = max(0.0, -math.sin(a))
        hem = -0.300 + wob * 0.030 + front * 0.074     # рваный подол
        prof = [(rim_r, rim_y), (0.345, -0.226), (0.302, hem)]
        left, right = [], []
        for (r, y) in prof:
            for (sign, dst) in ((-1.0, left), (1.0, right)):
                aa = a + sign * span * 0.5
                dst.append((math.cos(aa) * r, y, math.sin(aa) * r * 0.90))
        p.append(quad_strip(left, right, M_DRESS))
    return p


