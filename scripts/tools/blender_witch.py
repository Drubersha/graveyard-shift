def _rot(v, r):
    """Godot-совместимый поворот YXZ (градусы) вокруг локального нуля."""
    x, y, z = v
    rx, ry, rz = [math.radians(a) for a in r]
    c, s = math.cos(rz), math.sin(rz)
    x, y = x * c - y * s, x * s + y * c
    c, s = math.cos(rx), math.sin(rx)
    y, z = y * c - z * s, y * s + z * c
    c, s = math.cos(ry), math.sin(ry)
    x, z = x * c + z * s, -x * s + z * c
    return (x, y, z)


def box(size, pos, mat, rot=(0, 0, 0)):
    hx, hy, hz = size[0] / 2.0, size[1] / 2.0, size[2] / 2.0
    raw = [(-hx, -hy, -hz), (hx, -hy, -hz), (hx, -hy, hz), (-hx, -hy, hz),
           (-hx, hy, -hz), (hx, hy, -hz), (hx, hy, hz), (-hx, hy, hz)]
    verts = [tuple(a + b for a, b in zip(_rot(v, rot), pos)) for v in raw]
    faces = [(0, 1, 2, 3), (7, 6, 5, 4), (0, 4, 5, 1),
             (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]
    return (verts, faces, mat)


def prism(rings, sides, mat, pos=(0, 0, 0)):
    """Гранёная призма по кольцам (радиус_X, Y, радиус_Z)."""
    verts, faces, loops = [], [], []
    for (rx, y, rz) in rings:
        idx = []
        for i in range(sides):
            a = TAU * (i + 0.5) / sides
            idx.append(len(verts))
            verts.append((math.cos(a) * rx + pos[0], y + pos[1], math.sin(a) * rz + pos[2]))
        loops.append(idx)
    for li in range(len(loops) - 1):
        lo, hi = loops[li], loops[li + 1]
        for i in range(sides):
            j = (i + 1) % sides
            faces.append((lo[i], hi[i], hi[j], lo[j]))
    cb = len(verts)
    verts.append((pos[0], rings[0][1] + pos[1], pos[2]))
    ct = len(verts)
    verts.append((pos[0], rings[-1][1] + pos[1], pos[2]))
    for i in range(sides):
        j = (i + 1) % sides
        faces.append((cb, loops[0][j], loops[0][i]))
        faces.append((ct, loops[-1][i], loops[-1][j]))
    return (verts, faces, mat)


def _norm(v):
    l = math.sqrt(sum(c * c for c in v))
    return tuple(c / l for c in v) if l > 1e-9 else (0.0, 0.0, 1.0)


def _cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def sweep(points, radii, sides, mat):
    """Труба по ломаной — гнутая тулья шляпы, пряди волос, нос."""
    verts, faces, loops = [], [], []
    n = len(points)
    for i, p in enumerate(points):
        if i == 0:
            d = [points[1][k] - points[0][k] for k in range(3)]
        elif i == n - 1:
            d = [points[-1][k] - points[-2][k] for k in range(3)]
        else:
            d = [points[i + 1][k] - points[i - 1][k] for k in range(3)]
        d = _norm(d)
        up = (1.0, 0.0, 0.0) if abs(d[1]) > 0.95 else (0.0, 1.0, 0.0)
        u = _norm(_cross(d, up))
        v = _norm(_cross(d, u))
        ru, rv = radii[i]
        idx = []
        for k in range(sides):
            a = TAU * (k + 0.5) / sides
            ca, sa = math.cos(a) * ru, math.sin(a) * rv
            idx.append(len(verts))
            verts.append(tuple(p[j] + u[j] * ca + v[j] * sa for j in range(3)))
        loops.append(idx)
    for li in range(len(loops) - 1):
        lo, hi = loops[li], loops[li + 1]
        for k in range(sides):
            j = (k + 1) % sides
            faces.append((lo[k], hi[k], hi[j], lo[j]))
    cb = len(verts)
    verts.append(tuple(points[0]))
    ct = len(verts)
    verts.append(tuple(points[-1]))
    for k in range(sides):
        j = (k + 1) % sides
        faces.append((cb, loops[0][j], loops[0][k]))
        faces.append((ct, loops[-1][k], loops[-1][j]))
    return (verts, faces, mat)


def quad_strip(left, right, mat, thick=0.014):
    """Панель юбки: две вертикальные ломаные (внутренний край слева и справа)
    разводятся на толщину ткани. Нужна, чтобы между клиньями были ЩЕЛИ —
    сквозь них и видно шутку под юбкой."""
    verts, faces = [], []
    n = len(left)
    for side in (-0.5, 0.5):
        for i in range(n):
            for p in (left[i], right[i]):
                d = _norm((p[0], 0.0, p[2]))
                verts.append((p[0] + d[0] * thick * side, p[1], p[2] + d[2] * thick * side))
    inner, outer = 0, 2 * n
    for i in range(n - 1):
        a, b = inner + i * 2, inner + (i + 1) * 2
        faces.append((a, a + 1, b + 1, b))                 # внутренняя сторона
        a, b = outer + i * 2, outer + (i + 1) * 2
        faces.append((b, b + 1, a + 1, a))                 # наружная
        faces.append((inner + i * 2, outer + i * 2, outer + (i + 1) * 2, inner + (i + 1) * 2))
        faces.append((inner + i * 2 + 1, inner + (i + 1) * 2 + 1,
                      outer + (i + 1) * 2 + 1, outer + i * 2 + 1))
    faces.append((inner, inner + 1, outer + 1, outer))     # верхний торец
    faces.append((inner + (n - 1) * 2 + 1, inner + (n - 1) * 2,
                  outer + (n - 1) * 2, outer + (n - 1) * 2 + 1))
    return (verts, faces, mat)


def plate(grid, mat, thick=0.030):
    """Плита по сетке точек с толщиной — маска лица.

    Без неё лицо оставалось паковым: под полем шляпы оно уходило в тень, и на
    кадре читались только нос и губы, висящие в темноте. Своя плита даёт
    светлое поле, на котором есть что читать."""
    rows, cols = len(grid), len(grid[0])

    def idx(layer, r, c):
        return layer * rows * cols + r * cols + c

    verts = []
    for dz in (0.0, thick):
        for r in range(rows):
            for c in range(cols):
                p = grid[r][c]
                verts.append((p[0], p[1], p[2] + dz))
    faces = []
    for r in range(rows - 1):
        for c in range(cols - 1):
            faces.append((idx(0, r, c), idx(0, r + 1, c), idx(0, r + 1, c + 1), idx(0, r, c + 1)))
            faces.append((idx(1, r, c + 1), idx(1, r + 1, c + 1), idx(1, r + 1, c), idx(1, r, c)))
    for c in range(cols - 1):
        faces.append((idx(0, 0, c + 1), idx(0, 0, c), idx(1, 0, c), idx(1, 0, c + 1)))
        faces.append((idx(0, rows - 1, c), idx(0, rows - 1, c + 1), idx(1, rows - 1, c + 1), idx(1, rows - 1, c)))
    for r in range(rows - 1):
        faces.append((idx(0, r, 0), idx(0, r + 1, 0), idx(1, r + 1, 0), idx(1, r, 0)))
        faces.append((idx(0, r + 1, cols - 1), idx(0, r, cols - 1), idx(1, r, cols - 1), idx(1, r + 1, cols - 1)))
    return (verts, faces, mat)


def xform(chunk, rot=(0, 0, 0), pos=(0, 0, 0)):
    vs, fs, mi = chunk
    return ([tuple(a + b for a, b in zip(_rot(v, rot), pos)) for v in vs], fs, mi)


